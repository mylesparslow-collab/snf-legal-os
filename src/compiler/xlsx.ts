import { strToU8, zipSync } from 'fflate';

/** Style ids: 0 plain, 1 date, 2 percent-style number, 3 bold, 4 wrapped text, 5 money */
export type Style = 0 | 1 | 2 | 3 | 4 | 5;
export interface Cell {
  v?: string | number;
  /** Formula without the leading "=". */
  f?: string;
  s?: Style;
}
export interface Sheet {
  name: string;
  rows: (Cell | string | number | null)[][];
  widths?: number[];
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
export const colName = (i: number) => {
  let s = '';
  for (i += 1; i > 0; i = Math.floor((i - 1) / 26)) s = String.fromCharCode(65 + ((i - 1) % 26)) + s;
  return s;
};
/** Excel date serial (1900 system) for an ISO date. */
export const serial = (iso: string) => {
  const [y, m, d] = iso.split('-').map(Number);
  return (Date.UTC(y, m - 1, d) - Date.UTC(1899, 11, 30)) / 86_400_000;
};

function sheetXml(sh: Sheet): string {
  const rows = sh.rows
    .map((row, r) => {
      const cells = row
        .map((raw, c) => {
          if (raw == null || raw === '') return '';
          const cell: Cell = typeof raw === 'object' ? raw : { v: raw };
          const ref = `${colName(c)}${r + 1}`;
          const s = cell.s ? ` s="${cell.s}"` : '';
          if (cell.f) {
            const isStr = typeof cell.v === 'string';
            const v = cell.v == null ? '' : `<v>${esc(String(cell.v))}</v>`;
            return `<c r="${ref}"${s}${isStr ? ' t="str"' : ''}><f>${esc(cell.f)}</f>${v}</c>`;
          }
          if (typeof cell.v === 'number') return `<c r="${ref}"${s}><v>${cell.v}</v></c>`;
          return `<c r="${ref}"${s} t="inlineStr"><is><t xml:space="preserve">${esc(String(cell.v ?? ''))}</t></is></c>`;
        })
        .join('');
      return `<row r="${r + 1}">${cells}</row>`;
    })
    .join('');
  const cols = sh.widths?.length
    ? `<cols>${sh.widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('')}</cols>`
    : '';
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>${cols}<sheetData>${rows}</sheetData></worksheet>`;
}

